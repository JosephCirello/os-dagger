"""Ask OS DAGGER a doctrine question and get an answer that cites pub and page.

    python ask.py "What are the principles of sustainment?"
    python ask.py --retrieve-only "movement control responsibilities"   # no model, no key
    python ask.py                                                       # interactive
    python ask.py --pub "ATP 3-35" "who approves the TPFDD"             # restrict to one pub

The answer is generated by any OpenAI-compatible chat endpoint. Set these in
.env (see .env.example):

    DAGGER_BASE_URL   e.g. https://api.x.ai/v1  |  https://api.openai.com/v1  |  http://localhost:11434/v1
    DAGGER_API_KEY    the key for that endpoint (Ollama accepts any string)
    DAGGER_MODEL      e.g. grok-4  |  gpt-5.5  |  llama3.1

Retrieval is local and free. The model only ever sees the retrieved excerpts.
"""

from __future__ import annotations

import argparse
import sys

from dagger_common import cite, env_or, open_collection

SYSTEM_PROMPT = """You answer questions about U.S. Army doctrine for a commander or staff officer.
Rules:
1. Use only the doctrine excerpts provided. No outside knowledge, no guessing.
2. Cite every claim with the source tag exactly as given, for example [ATP 3-35, p. 42].
3. If the excerpts do not answer the question, say so plainly and name the closest thing they do say.
4. Be precise and brief. Military register. No preamble, no filler."""


def retrieve(question: str, k: int, pub: str | None):
    col = open_collection()
    where = {"pub": pub} if pub else None
    res = col.query(query_texts=[question], n_results=k, where=where, include=["documents", "metadatas", "distances"])
    hits = []
    for doc, meta, dist in zip(res["documents"][0], res["metadatas"][0], res["distances"][0]):
        hits.append({"text": doc, "meta": meta, "score": 1.0 - dist})  # cosine similarity
    return hits


def build_context(hits) -> str:
    parts = []
    for h in hits:
        parts.append(f"[{cite(h['meta'])}]\n{h['text']}")
    return "\n\n---\n\n".join(parts)


def generate(question: str, context: str) -> str:
    from dotenv import load_dotenv
    from openai import OpenAI

    load_dotenv()
    base_url = env_or("DAGGER_BASE_URL")
    api_key = env_or("DAGGER_API_KEY")
    model = env_or("DAGGER_MODEL")
    missing = [n for n, v in (("DAGGER_BASE_URL", base_url), ("DAGGER_API_KEY", api_key), ("DAGGER_MODEL", model)) if not v]
    if missing:
        sys.exit(f"Missing {', '.join(missing)}. Copy .env.example to .env and fill it in, or use --retrieve-only.")

    client = OpenAI(api_key=api_key, base_url=base_url)
    completion = client.chat.completions.create(
        model=model,
        messages=[
            {"role": "system", "content": SYSTEM_PROMPT},
            {"role": "user", "content": f"Question: {question}\n\nDoctrine excerpts:\n\n{context}"},
        ],
        max_tokens=1500,
    )
    return (completion.choices[0].message.content or "").strip()


def answer(question: str, k: int, pub: str | None, retrieve_only: bool, show: bool) -> None:
    hits = retrieve(question, k, pub)
    if not hits:
        print("Nothing retrieved. Is the index built? Run: python build_index.py")
        return
    if show or retrieve_only:
        for i, h in enumerate(hits, 1):
            print(f"\n[{i}] {cite(h['meta'])}  similarity {h['score']:.3f}  ({h['meta']['title']})")
            print(h["text"][:600].replace("\n", " ") + ("..." if len(h["text"]) > 600 else ""))
        print()
    if retrieve_only:
        return
    print(generate(question, build_context(hits)))
    print("\nSources:")
    for h in hits:
        print(f"  {cite(h['meta'])}  {h['meta']['title']}  (similarity {h['score']:.3f})")


def main() -> None:
    ap = argparse.ArgumentParser(description=__doc__, formatter_class=argparse.RawDescriptionHelpFormatter)
    ap.add_argument("question", nargs="?", help="the question; omit for an interactive session")
    ap.add_argument("-k", type=int, default=6, help="how many excerpts to retrieve (default 6)")
    ap.add_argument("--pub", help='restrict retrieval to one publication, e.g. "FM 6-0"')
    ap.add_argument("--retrieve-only", action="store_true", help="print the retrieved excerpts and stop; needs no API key")
    ap.add_argument("--show", action="store_true", help="print the retrieved excerpts before the answer")
    args = ap.parse_args()

    if args.question:
        answer(args.question, args.k, args.pub, args.retrieve_only, args.show)
        return

    print("OS DAGGER. Ask a doctrine question. Type q to quit.")
    while True:
        try:
            q = input("\n> ").strip()
        except (EOFError, KeyboardInterrupt):
            print()
            break
        if q.lower() in {"q", "quit", "exit"}:
            break
        if q:
            answer(q, args.k, args.pub, args.retrieve_only, args.show)


if __name__ == "__main__":
    main()
