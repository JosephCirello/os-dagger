"""Ask OS DAGGER a doctrine question and get an answer that cites pub and page.

    python ask.py "What are the principles of sustainment?"
    python ask.py --retrieve-only "movement control responsibilities"   # no model, no key
    python ask.py                                                       # interactive
    python ask.py --pub "ATP 3-35" "who approves the TPFDD"             # restrict to one pub

The answer is generated by any OpenAI-compatible chat endpoint. Set these in
.env (see .env.example):

    DAGGER_BASE_URL   e.g. https://api.x.ai/v1  |  https://api.openai.com/v1  |  http://localhost:11434/v1
    DAGGER_API_KEY    the key for that endpoint (Ollama accepts any string)
    DAGGER_MODEL      e.g. grok-4.7  |  gpt-5.5  |  llama3.1

Retrieval is local and free. The model only ever sees the retrieved excerpts.
"""

from __future__ import annotations

import argparse
import re
import sys

from dagger_common import cite, env_or, locate, open_collection

SYSTEM_PROMPT = """You answer questions about U.S. Army doctrine for a commander or staff officer.
Rules:
1. Use only the doctrine excerpts provided. No outside knowledge, no guessing.
2. Cite every claim with the source tag exactly as given, for example [ATP 3-35, p. 3-7].
3. If the excerpts answer only part of the question, give that part first, with citations, then say in one line what they do not cover.
4. If the excerpts do not answer it at all, say so plainly and name the closest thing they do say.
5. Be precise and brief. Military register. No preamble, no filler."""


STOPWORDS = set("""a an and are as at be by for from how in is it of on or that the this to
what when where which who why will with does do must may can should its their there""".split())


def key_terms(question: str) -> list[str]:
    words = re.findall(r"[a-z0-9][a-z0-9\-]+", question.lower())
    return [w for w in words if w not in STOPWORDS and len(w) > 2]


_CORPUS: dict | None = None


def load_corpus(col) -> dict:
    """Every chunk, tokenized once per process, for the lexical pass."""
    global _CORPUS
    if _CORPUS is None:
        got = col.get(include=["documents", "metadatas"])
        docs = got["documents"]
        toks = [re.findall(r"[a-z0-9][a-z0-9\-]+", d.lower()) for d in docs]
        df: dict[str, int] = {}
        for t in toks:
            for w in set(t):
                df[w] = df.get(w, 0) + 1
        _CORPUS = {
            "ids": got["ids"], "docs": docs, "metas": got["metadatas"], "toks": toks, "df": df,
            "avg_len": sum(len(t) for t in toks) / max(len(toks), 1),
        }
    return _CORPUS


def bm25_rank(question: str, corpus: dict, pub: str | None, n: int) -> list[int]:
    """Indices of the top-n chunks by BM25 for the question's key terms."""
    import math

    terms = key_terms(question)
    if not terms:
        return []
    N = len(corpus["docs"])
    k1, b = 1.5, 0.75
    scores = []
    for i, toks in enumerate(corpus["toks"]):
        if pub and corpus["metas"][i]["pub"] != pub:
            continue
        L = len(toks)
        if not L:
            continue
        tf: dict[str, int] = {}
        for w in toks:
            if w in terms:
                tf[w] = tf.get(w, 0) + 1
        if not tf:
            continue
        s = 0.0
        for w, f in tf.items():
            idf = math.log(1 + (N - corpus["df"][w] + 0.5) / (corpus["df"][w] + 0.5))
            s += idf * (f * (k1 + 1)) / (f + k1 * (1 - b + b * L / corpus["avg_len"]))
        scores.append((s, i))
    scores.sort(reverse=True)
    return [i for _, i in scores[:n]]


def retrieve(question: str, k: int, pub: str | None):
    """Hybrid search: vector similarity and BM25 keyword ranking, fused by
    reciprocal rank. Doctrine lives on exact terms ("tenets", "OPORD", "TPFDD")
    that a small embedding model blurs; the lexical pass catches those pages,
    the vector pass catches paraphrase. Each list contributes its top 3k.
    """
    col = open_collection()
    corpus = load_corpus(col)
    pool = max(k * 3, 20)
    where = {"pub": pub} if pub else None
    res = col.query(query_texts=[question], n_results=pool, where=where, include=["metadatas", "distances"])
    id_pos = {cid: i for i, cid in enumerate(corpus["ids"])}
    fused: dict[int, dict] = {}
    for r, (cid, dist) in enumerate(zip(res["ids"][0], res["distances"][0]), start=1):
        i = id_pos[cid]
        fused.setdefault(i, {"rrf": 0.0, "sim": None})
        fused[i]["rrf"] += 1.0 / (60 + r)
        fused[i]["sim"] = 1.0 - dist
    for r, i in enumerate(bm25_rank(question, corpus, pub, pool), start=1):
        fused.setdefault(i, {"rrf": 0.0, "sim": None})
        fused[i]["rrf"] += 1.0 / (60 + r)
    order = sorted(fused.items(), key=lambda kv: kv[1]["rrf"], reverse=True)[:k]
    hits = []
    for i, f in order:
        hits.append({"text": corpus["docs"][i], "meta": corpus["metas"][i], "score": f["sim"]})
    return hits


def build_context(hits) -> str:
    parts = []
    for h in hits:
        parts.append(f"[{cite(h['meta'])}]\n{h['text']}")
    return "\n\n---\n\n".join(parts)


def generate(question: str, context: str) -> str:
    from dotenv import load_dotenv
    from openai import OpenAI

    load_dotenv()
    base_url = env_or("DAGGER_BASE_URL")
    api_key = env_or("DAGGER_API_KEY")
    model = env_or("DAGGER_MODEL")
    missing = [n for n, v in (("DAGGER_BASE_URL", base_url), ("DAGGER_API_KEY", api_key), ("DAGGER_MODEL", model)) if not v]
    if missing:
        sys.exit(f"Missing {', '.join(missing)}. Copy .env.example to .env and fill it in, or use --retrieve-only.")

    client = OpenAI(api_key=api_key, base_url=base_url)
    completion = client.chat.completions.create(
        model=model,
        messages=[
            {"role": "system", "content": SYSTEM_PROMPT},
            {"role": "user", "content": f"Question: {question}\n\nDoctrine excerpts:\n\n{context}"},
        ],
        max_tokens=1500,
    )
    return (completion.choices[0].message.content or "").strip()


def answer(question: str, k: int, pub: str | None, retrieve_only: bool, show: bool) -> None:
    hits = retrieve(question, k, pub)
    if not hits:
        print("Nothing retrieved. Is the index built? Run: python build_index.py")
        return
    if show or retrieve_only:
        for i, h in enumerate(hits, 1):
            print(f"\n[{i}] {cite(h['meta'])}  {h['meta']['title']}  ({locate(h['meta'])}, {match_label(h)})")
            print(h["text"][:600].replace("\n", " ") + ("..." if len(h["text"]) > 600 else ""))
        print()
    if retrieve_only:
        return
    print(generate(question, build_context(hits)))
    print("\nSources:")
    for h in hits:
        print(f"  {cite(h['meta']):22} {h['meta']['title']}  ({locate(h['meta'])}, {match_label(h)})")


def match_label(hit: dict) -> str:
    """'similarity 0.612' when the vector pass found it, 'keyword match' when only BM25 did."""
    return f"similarity {hit['score']:.3f}" if hit["score"] is not None else "keyword match"


def main() -> None:
    ap = argparse.ArgumentParser(description=__doc__, formatter_class=argparse.RawDescriptionHelpFormatter)
    ap.add_argument("question", nargs="?", help="the question; omit for an interactive session")
    ap.add_argument("-k", type=int, default=8, help="how many excerpts to retrieve (default 8)")
    ap.add_argument("--pub", help='restrict retrieval to one publication, e.g. "FM 6-0"')
    ap.add_argument("--retrieve-only", action="store_true", help="print the retrieved excerpts and stop; needs no API key")
    ap.add_argument("--show", action="store_true", help="print the retrieved excerpts before the answer")
    args = ap.parse_args()

    if args.question:
        answer(args.question, args.k, args.pub, args.retrieve_only, args.show)
        return

    print("OS DAGGER. Ask a doctrine question. Type q to quit.")
    while True:
        try:
            q = input("\n> ").strip()
        except (EOFError, KeyboardInterrupt):
            print()
            break
        if q.lower() in {"q", "quit", "exit"}:
            break
        if q:
            answer(q, args.k, args.pub, args.retrieve_only, args.show)


if __name__ == "__main__":
    main()
